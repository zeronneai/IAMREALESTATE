let lang = 'en'
const listeners = new Set()

export function getLang() { return lang }
export function t(key, vars) {
  const entry = dict[key]
  let s = entry ? entry[lang === 'es' ? 1 : 0] : key
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k])
  return s
}
export function onLang(fn) { listeners.add(fn) }

export function applyLang(next) {
  lang = next === 'es' ? 'es' : 'en'
  try { localStorage.setItem('iam-lang', lang) } catch (e) { /* storage unavailable */ }
  document.documentElement.lang = lang
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n) })
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml) })
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh) })
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)))
  listeners.forEach(fn => fn(lang))
}

export function initialLang() {
  const q = new URLSearchParams(location.search).get('lang')
  if (q) return q
  try { const s = localStorage.getItem('iam-lang'); if (s) return s } catch (e) { /* ignore */ }
  return 'en'
}
